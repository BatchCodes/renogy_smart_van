esp_err_t Jd79656Panel::reset() {
    io_.hardware_reset();
    ESP_RETURN_ON_ERROR(io_.wait_while_busy(kBusyLevel, kFastRefreshTimeoutMs), kTag, "reset");
    // The Meshtastic driver sends 0x12 after each reset. Keep the same sequence.
    ESP_RETURN_ON_ERROR(io_.command(0x12), kTag, "reset command");
    return io_.wait_while_busy(kBusyLevel, kFullRefreshTimeoutMs);
}

esp_err_t Jd79656Panel::refresh_and_power_off(std::uint32_t timeout_ms) {
    ESP_RETURN_ON_ERROR(io_.command(0x04), kTag, "power on");
    ESP_RETURN_ON_ERROR(io_.wait_while_busy(kBusyLevel, kFastRefreshTimeoutMs), kTag, "power on");
    ESP_RETURN_ON_ERROR(io_.command(0x12), kTag, "refresh");
    ESP_RETURN_ON_ERROR(io_.wait_while_busy(kBusyLevel, timeout_ms), kTag, "refresh");
    ESP_RETURN_ON_ERROR(io_.command(0x02), kTag, "power off");
    return io_.wait_while_busy(kBusyLevel, kFastRefreshTimeoutMs);
}

esp_err_t Jd79656Panel::show_full(std::span<const std::uint8_t> frame) {
    ESP_RETURN_ON_ERROR(reset(), kTag, "reset");
    // Panel setting: 122 x 250, black and white, scan directions, waveform from OTP.
    ESP_RETURN_ON_ERROR(io_.command(0x00, {0xDF}), kTag, "panel setting");
    // Border white, default data polarity and interval.
    ESP_RETURN_ON_ERROR(io_.command(0x50, {0x97}), kTag, "VCOM interval");
    ESP_RETURN_ON_ERROR(io_.command(0x13), kTag, "new image");
    ESP_RETURN_ON_ERROR(io_.data(frame), kTag, "new image");
    ESP_RETURN_ON_ERROR(io_.command(0x10), kTag, "old image");
    ESP_RETURN_ON_ERROR(io_.data(frame), kTag, "old image");
    return refresh_and_power_off(kFullRefreshTimeoutMs);
}

esp_err_t Jd79656Panel::show_fast(std::span<const std::uint8_t> previous,
                                  std::span<const std::uint8_t> frame) {
    ESP_RETURN_ON_ERROR(reset(), kTag, "reset");
    // Panel setting as for a full refresh, but with the waveform from the registers below.
    ESP_RETURN_ON_ERROR(io_.command(0x00, {0xFF}), kTag, "panel setting");
    // Border floating.
    ESP_RETURN_ON_ERROR(io_.command(0x50, {0xD7}), kTag, "VCOM interval");
    ESP_RETURN_ON_ERROR(io_.command(0x20), kTag, "VCOM waveform");
    ESP_RETURN_ON_ERROR(io_.data(kFastVcom), kTag, "VCOM waveform");
    ESP_RETURN_ON_ERROR(io_.command(0x21), kTag, "WW waveform");
    ESP_RETURN_ON_ERROR(io_.data(kFastWhiteToWhite), kTag, "WW waveform");
    ESP_RETURN_ON_ERROR(io_.command(0x22), kTag, "BW waveform");
    ESP_RETURN_ON_ERROR(io_.data(kFastBlackToWhite), kTag, "BW waveform");
    ESP_RETURN_ON_ERROR(io_.command(0x23), kTag, "WB waveform");
    ESP_RETURN_ON_ERROR(io_.data(kFastWhiteToBlack), kTag, "WB waveform");
    ESP_RETURN_ON_ERROR(io_.command(0x24), kTag, "BB waveform");
    ESP_RETURN_ON_ERROR(io_.data(kFastBlackToBlack), kTag, "BB waveform");
    ESP_RETURN_ON_ERROR(io_.command(0x10), kTag, "old image");
    ESP_RETURN_ON_ERROR(io_.data(previous), kTag, "old image");
    ESP_RETURN_ON_ERROR(io_.command(0x13), kTag, "new image");
    ESP_RETURN_ON_ERROR(io_.data(frame), kTag, "new image");
    return refresh_and_power_off(kFastRefreshTimeoutMs);
}

esp_err_t Jd79656Panel::sleep() {
    // Each refresh already ends with the panel power off. The controller deep sleep
    // command is not documented for this controller, so it is not used.
    return ESP_OK;
}

